#!/usr/bin/env python3
"""Generate docs/platform-foundation/SCHEMA_COVERAGE_APPENDIX.md.

Installs INSTALL_FOUNDATION.sql into a throwaway database on a DISPOSABLE
server, then maps every table/column of the two source specifications to the
implemented column (type, nullability) and lists each table's constraints,
triggers and policies. The database is dropped afterwards.

Usage (opt-in, never against a real database):
  COB3_TEST_DISPOSABLE_SERVER=1 COB3_TEST_ADMIN_DSN="host=localhost port=55432 user=pgsuper dbname=postgres" \
      python tools/schema_coverage.py
"""
from __future__ import annotations

import os
import pathlib
import sys
import uuid

import psycopg2

PKG = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PKG / "tests"))
from spec_parser import parse_identity_spec, parse_tenant_spec  # noqa: E402

OUT = PKG.parents[1] / "docs" / "platform-foundation" / "SCHEMA_COVERAGE_APPENDIX.md"
ADMIN_DSN = os.environ.get("COB3_TEST_ADMIN_DSN", "host=localhost port=55432 user=pgsuper dbname=postgres")
KIND = {"p": "PK", "u": "UNIQUE", "f": "FK", "c": "CHECK", "x": "EXCLUDE", "t": "CONSTRAINT TRIGGER"}


def main() -> int:
    if os.environ.get("COB3_TEST_DISPOSABLE_SERVER") != "1":
        print("Refusing to run: set COB3_TEST_DISPOSABLE_SERVER=1 for a disposable server.")
        return 2
    admin = psycopg2.connect(ADMIN_DSN)
    admin.autocommit = True
    db = "cob3_cov_" + uuid.uuid4().hex[:8]
    admin.cursor().execute(f'CREATE DATABASE "{db}"')
    try:
        parts = dict(p.split("=", 1) for p in ADMIN_DSN.split())
        parts["dbname"] = db
        conn = psycopg2.connect(" ".join(f"{k}={v}" for k, v in parts.items()))
        conn.autocommit = True
        cur = conn.cursor()
        cur.execute((PKG / "INSTALL_FOUNDATION.sql").read_text(encoding="utf-8"))
        lines = render(cur)
        conn.close()
    finally:
        admin.cursor().execute(f'DROP DATABASE IF EXISTS "{db}"')
        admin.close()
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


def render(cur) -> list[str]:
    specs = {"cob3_tenant": parse_tenant_spec(), "cob3_identity": parse_identity_spec()}
    cur.execute("select script_checksum from cob3_tenant.foundation_installations where component = 'foundation'")
    checksum = cur.fetchone()[0]
    out = ["# Schema coverage appendix (generated)", "",
           f"Generated by `database/syskriti_foundation/tools/schema_coverage.py` from the two source specifications and a live",
           f"installation of `INSTALL_FOUNDATION.sql` (checksum `{checksum[:16]}…`). Do not edit by hand.", "",
           "Legend: every specified column is listed as `name type [NN]` (NN = NOT NULL) followed by the implementation",
           "status. `=` means the implemented column has exactly the specified type and nullability.", ""]
    totals = [0, 0]
    for schema in ("cob3_tenant", "cob3_identity"):
        out += [f"## {schema}", ""]
        for table, cols in specs[schema].items():
            cur.execute("""select a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull
                             from pg_attribute a where a.attrelid = %s::regclass and a.attnum > 0 and not a.attisdropped""",
                        (f"{schema}.{table}",))
            actual = {r[0]: (r[1], r[2]) for r in cur.fetchall()}
            out += [f"### `{schema}.{table}`", ""]
            col_items = []
            for col, spec in cols.items():
                totals[0] += 1
                status = "=" if actual.get(col) == spec else f"MISMATCH {actual.get(col)}"
                if status == "=":
                    totals[1] += 1
                col_items.append(f"`{col} {spec[0]}{' NN' if spec[1] else ''}` {status}")
            out.append("Columns: " + "; ".join(col_items) + ".")
            extra = sorted(set(actual) - set(cols))
            if extra:
                out.append(f"Unspecified extra columns: {', '.join(extra)}.")
            cur.execute("""select contype, string_agg(conname, ', ' order by conname) from pg_constraint
                            where conrelid = %s::regclass and contype <> 'n' group by contype order by contype""",
                        (f"{schema}.{table}",))
            for contype, names in cur.fetchall():
                out.append(f"- {KIND.get(contype, contype)}: {names}")
            cur.execute("""select string_agg(c.relname, ', ' order by c.relname) from pg_index i join pg_class c on c.oid = i.indexrelid
                            where i.indrelid = %s::regclass and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)""",
                        (f"{schema}.{table}",))
            idx = cur.fetchone()[0]
            if idx:
                out.append(f"- Indexes: {idx}")
            cur.execute("""select string_agg(tgname, ', ' order by tgname) from pg_trigger
                            where tgrelid = %s::regclass and not tgisinternal""", (f"{schema}.{table}",))
            out.append(f"- Triggers: {cur.fetchone()[0] or 'none'}")
            cur.execute("""select string_agg(policyname || ' [' || cmd || ' ' || array_to_string(roles, '/') || ']', ', ' order by policyname)
                             from pg_policies where schemaname = %s and tablename = %s""", (schema, table))
            out.append(f"- Policies (RLS enabled + forced): {cur.fetchone()[0]}")
            out.append("")
    out.insert(7, f"**Result: {totals[1]}/{totals[0]} specified columns implemented exactly as specified across "
                  f"{sum(len(v) for v in specs.values())} tables.**")
    out.insert(8, "")
    return out


if __name__ == "__main__":
    sys.exit(main())
