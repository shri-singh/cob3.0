#!/usr/bin/env python3
"""Deterministic build of the ordered upgrade migrations (002, 003, ...).

Each migration has a single source of truth: the ordered fragments in
``src_migrations/<NNN>_<name>/NN_*.sql``. Like the foundation installer, the
fragments form ONE PL/pgSQL ``DO`` block, so every migration is a single atomic
statement that runs unchanged in DBeaver, pgAdmin or psql: it applies
completely or changes nothing.

Outputs (LF line endings):
  migrations/002_settings_catalog_workspace.sql
  migrations/003_ai_agent_state.sql

Usage:
  python build_migrations.py           # (re)build all migrations
  python build_migrations.py --check   # exit 1 if committed outputs drift from src_migrations/

Each migration embeds a SHA-256 checksum of its own normalized text (computed
with the placeholder in place). Its rerun guard compares it with the checksum
recorded in cob3_tenant.foundation_installations for its component.
"""
from __future__ import annotations

import hashlib
import sys
from dataclasses import dataclass
from pathlib import Path

PLACEHOLDER = "@@MIGRATION_CHECKSUM@@"
ROOT = Path(__file__).resolve().parent


@dataclass(frozen=True)
class Migration:
    number: str
    component: str
    version: str
    title: str
    schemas: str
    requires: str
    tables: str

    @property
    def src(self) -> Path:
        return ROOT / "src_migrations" / f"{self.number}_{self.component}"

    @property
    def output(self) -> Path:
        return ROOT / "migrations" / f"{self.number}_{self.component}.sql"

    @property
    def dollar_tag(self) -> str:
        return f"$syskriti_m{self.number}$"


MIGRATIONS = (
    Migration(
        number="002",
        component="settings_catalog_workspace",
        version="1.1.0",
        title="SETTINGS, CATALOG AND WORKSPACE MODULES + IDENTITY AMENDMENTS",
        schemas="cob3_settings, cob3_catalog, cob3_workspace (+ cob3_identity amendments)",
        requires="foundation 1.0.0 (migrations/001_initial_foundation.sql)",
        tables="11 Settings + 10 Catalog + 16 Workspace + 2 Identity tables",
    ),
    Migration(
        number="003",
        component="ai_agent_state",
        version="1.2.0",
        title="AI AND AGENT STATE MODULES",
        schemas="cob3_agent, cob3_ai_runtime, cob3_copilot, cob3_memory, cob3_learning, cob3_llmobs, cob3_ai_lineage, cob3_connectors",
        requires="foundation 1.0.0 + migration 002 (settings_catalog_workspace 1.1.0)",
        tables="66 AI tables + cob3_connectors.source_scope_bindings",
    ),
)

HEADER = """\
-- =============================================================================
-- SYSKRITI FOUNDATION -- ORDERED UPGRADE MIGRATION {number}
-- {title}
-- Component        : {component}
-- Version          : {version}
-- Checksum (sha256): {checksum}
-- Schemas          : {schemas}
-- Tables           : {tables}
-- Requires         : {requires}
-- Generated by     : database/syskriti_foundation/build_migrations.py from
--                    src_migrations/{number}_{component}/*.sql
--                    DO NOT EDIT THIS FILE BY HAND. Edit the fragments and rebuild.
-- -----------------------------------------------------------------------------
-- HOW TO RUN (DBeaver / pgAdmin / psql):
--   1. Connect to the database that already holds the foundation, as the same
--      migration role that installed it (a member of cob3_owner).
--   2. Execute this whole file. It is ONE atomic statement (a single DO block):
--      it either applies everything or changes nothing.
-- Re-running: if this exact component version/checksum is recorded it is a
-- verified no-op; any other existing state fails early without changes.
-- Error locations: PL/pgSQL reports "line N" relative to the DO block; the
-- corresponding file line is N + {offset}.
-- =============================================================================
"""


def _read_fragments(m: Migration) -> str:
    parts = []
    paths = sorted(m.src.glob("[0-9][0-9]_*.sql"))
    if not paths:
        raise SystemExit(f"no fragments found in {m.src}")
    for path in paths:
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
        if m.dollar_tag in text:
            raise SystemExit(f"{path.name}: must not contain the outer dollar-quote tag {m.dollar_tag}")
        parts.append(f"-- >>> src_migrations/{m.src.name}/{path.name}\n{text}\n")
    body = "\n".join(parts)
    # Blank lines become empty comments so SQL editors that treat blank lines as
    # statement delimiters never split the DO block.
    return "\n".join(line if line.strip() else "--" for line in body.split("\n"))


def build_text(m: Migration) -> str:
    body = _read_fragments(m)
    fields = dict(number=m.number, title=m.title, component=m.component, version=m.version,
                  schemas=m.schemas, tables=m.tables, requires=m.requires, checksum=PLACEHOLDER)
    offset = HEADER.format(offset=0, **fields).count("\n")
    header = HEADER.format(offset=offset, **fields)
    text = f"{header}DO {m.dollar_tag}\n{body}\n{m.dollar_tag};\n"
    checksum = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return text.replace(PLACEHOLDER, checksum)


def main(argv: list[str]) -> int:
    drift = []
    for m in MIGRATIONS:
        text = build_text(m)
        checksum = text.split("Checksum (sha256): ")[1][:64]
        if "--check" in argv:
            current = m.output.read_text(encoding="utf-8").replace("\r\n", "\n") if m.output.exists() else None
            if current != text:
                drift.append(str(m.output.relative_to(ROOT)))
            else:
                print(f"OK: {m.output.relative_to(ROOT)} matches src ({checksum})")
            continue
        m.output.parent.mkdir(parents=True, exist_ok=True)
        m.output.write_bytes(text.encode("utf-8"))
        print(f"built {m.output.relative_to(ROOT)}; {text.count(chr(10))} lines; checksum {checksum}")
    if drift:
        print("DRIFT: rebuild required for: " + ", ".join(drift))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
