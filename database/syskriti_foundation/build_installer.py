#!/usr/bin/env python3
"""Deterministic build of the standalone Syskriti foundation installer.

Single source of truth: the ordered fragments in ``src/NN_*.sql``. They are
fragments of ONE PL/pgSQL ``DO`` block (so the whole installer is a single,
atomic statement that runs unchanged in DBeaver, pgAdmin or psql).

Outputs (byte-identical, LF line endings):
  INSTALL_FOUNDATION.sql
  migrations/001_initial_foundation.sql

Usage:
  python build_installer.py           # (re)build
  python build_installer.py --check   # fail (exit 1) if committed outputs drift from src/

The installer embeds a SHA-256 checksum of its own normalized text (computed
with the checksum placeholder in place). The rerun guard compares it with the
checksum recorded in cob3_tenant.foundation_installations.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

VERSION = "1.0.0"
SCHEMAS = ("cob3_tenant", "cob3_identity")  # single source for schema names in tooling
PLACEHOLDER = "@@INSTALLER_CHECKSUM@@"
DOLLAR_TAG = "$syskriti_foundation$"

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "src"
OUTPUTS = (ROOT / "INSTALL_FOUNDATION.sql", ROOT / "migrations" / "001_initial_foundation.sql")

HEADER = """\
-- =============================================================================
-- SYSKRITI REUSABLE SAAS FOUNDATION -- STANDALONE INSTALLER
-- Version          : {version}
-- Checksum (sha256): {checksum}
-- Schemas          : cob3_tenant, cob3_identity  (48 logical tables + 2 support tables)
-- Target           : an EXISTING PostgreSQL 15+ database (do not run CREATE DATABASE here)
-- Generated by     : database/syskriti_foundation/build_installer.py from src/*.sql
--                    DO NOT EDIT THIS FILE BY HAND. Edit src/ and rebuild.
-- -----------------------------------------------------------------------------
-- HOW TO RUN (DBeaver / pgAdmin / psql):
--   1. Connect to the target database as the migration role (database owner or a
--      role with CREATE on the database; CREATEROLE unless roles are pre-created).
--   2. Execute this whole file. It is ONE atomic statement (a single DO block):
--      it either installs everything or changes nothing.
--   3. Run VERIFY_FOUNDATION.sql (read-only).
-- Re-running: if this exact version/checksum is installed it is a verified
-- no-op; any other existing state fails early without changes.
-- Error locations: PL/pgSQL reports "line N" relative to the DO block; the
-- corresponding file line is N + {offset}.
-- Infrastructure exceptions created outside the two schemas: roles
-- cob3_owner, cob3_runtime, cob3_provisioner, cob3_commercial_admin (NOLOGIN,
-- no passwords) and extension btree_gist (schema public) if absent.
-- =============================================================================
"""


def _read_fragments() -> str:
    parts = []
    for path in sorted(SRC.glob("[0-9][0-9]_*.sql")):
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
        if DOLLAR_TAG in text:
            raise SystemExit(f"{path.name}: must not contain the outer dollar-quote tag {DOLLAR_TAG}")
        parts.append(f"-- >>> src/{path.name}\n{text}\n")
    if not parts:
        raise SystemExit("no src fragments found")
    body = "\n".join(parts)
    # Blank lines become empty comments so SQL editors configured to treat
    # blank lines as statement delimiters never split the DO block.
    return "\n".join(line if line.strip() else "--" for line in body.split("\n"))


def build_text() -> str:
    body = _read_fragments()
    header_probe = HEADER.format(version=VERSION, checksum=PLACEHOLDER, offset=0)
    # PL/pgSQL numbers DO-body lines from the text right after the opening tag
    # (body line 1 = the "DO $tag$" line), so file line = N + header line count.
    offset = header_probe.count("\n")
    header = HEADER.format(version=VERSION, checksum=PLACEHOLDER, offset=offset)
    text = f"{header}DO {DOLLAR_TAG}\n{body}\n{DOLLAR_TAG};\n"
    checksum = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return text.replace(PLACEHOLDER, checksum)


def main(argv: list[str]) -> int:
    text = build_text()
    if "--check" in argv:
        drift = []
        for out in OUTPUTS:
            current = out.read_text(encoding="utf-8").replace("\r\n", "\n") if out.exists() else None
            if current != text:
                drift.append(str(out.relative_to(ROOT)))
        if drift:
            print("DRIFT: rebuild required for: " + ", ".join(drift))
            return 1
        print("OK: installer and migration 001 match src/ (" + text.split("Checksum (sha256): ")[1][:64] + ")")
        return 0
    for out in OUTPUTS:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(text.encode("utf-8"))
    print(f"built {', '.join(str(o.relative_to(ROOT)) for o in OUTPUTS)}; "
          f"{text.count(chr(10))} lines; checksum {text.split('Checksum (sha256): ')[1][:64]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
